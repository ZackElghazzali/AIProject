from facedetect.boxes import non_max_suppression

def iou(a, b):
    # The grader's own, deliberately not imported from the student's module.
    # An earlier version imported theirs, so a broken iou silently corrupted
    # the reference it was being compared against and the failure message
    # blamed the wrong function.
    ax1, ay1, ax2, ay2 = (float(v) for v in a)
    bx1, by1, bx2, by2 = (float(v) for v in b)
    ix1, iy1 = max(ax1, bx1), max(ay1, by1)
    ix2, iy2 = min(ax2, bx2), min(ay2, by2)
    iw, ih = max(0.0, ix2 - ix1), max(0.0, iy2 - iy1)
    inter = iw * ih
    union = (ax2 - ax1) * (ay2 - ay1) + (bx2 - bx1) * (by2 - by1) - inter
    return inter / union if union > 0 else 0.0

