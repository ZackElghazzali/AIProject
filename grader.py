def _load(grade_dir: Path, name: str, result: LevelResult):
    """Read a probe's JSON, or fail the level with its recorded error."""
    import json
    err = grade_dir / f"{name}.error"
    if err.exists():
        result.status = "FAIL"
        result.add(_c("✗ " + err.read_text().strip(), C.RED))
        return None
    p = grade_dir / f"{name}.json"
    if not p.exists():
        result.status = "FAIL"
        result.add(_c("✗ the level did not run — is the function defined and returning?", C.RED))
        return None
    return json.loads(p.read_text())


def _iou(a, b) -> float:
    ax1, ay1, ax2, ay2 = a
    bx1, by1, bx2, by2 = b
    ix1, iy1 = max(ax1, bx1), max(ay1, by1)
    ix2, iy2 = min(ax2, bx2), min(ay2, by2)
    iw, ih = max(0.0, ix2 - ix1), max(0.0, iy2 - iy1)
    inter = iw * ih
    union = (ax2 - ax1) * (ay2 - ay1) + (bx2 - bx1) * (by2 - by1) - inter
    return inter / union if union > 0 else 0.0


def check_l1(grade_dir: Path, result: LevelResult) -> None:
    import csv
    d = _load(grade_dir, "L1_dets", result)
    if d is None:
        return
    w = result.weight
    earned = 0.0

    if not d["shape_ok"]:
        result.status = "FAIL"
        result.add(_c("✗ detect_objects must return a list of dicts with keys "
                      "'label', 'score' and 'box'", C.RED))
        return
    earned += 0.20 * w
    result.add(_c("✓ returns well-formed detections", C.GREEN))

    recs = d["records"]
    if not recs:
        result.status = "PARTIAL"
        result.earned = round(earned, 4)
        result.add(_c("✗ no detections at all on 8 scenes — the reference finds "
                      "about 20. Check that conf is a threshold, not a target, "
                      "and that the image reached the model in the colour order "
                      "it expects.", C.YELLOW))
        return

    truth = {}
    for r in csv.DictReader(open(PROVIDED / "scenes.csv")):
        truth.setdefault(r["filename"], []).append(
            (r["label"], (float(r["x1"]), float(r["y1"]), float(r["x2"]), float(r["y2"]))))
    by_file = {}
    for r in recs:
        by_file.setdefault(r["filename"], []).append(r)

    placed = matched = 0
    for fn in d["picks"]:
        for lbl, tb in truth.get(fn, []):
            placed += 1
            best = max((_iou(tb, (r["x1"], r["y1"], r["x2"], r["y2"]))
                        for r in by_file.get(fn, []) if r["label"] == lbl),
                       default=0.0)
            if best > L1_MIN_IOU:
                matched += 1
    recall = matched / placed if placed else 0.0

    if recall >= L1_MIN_RECALL:
        earned += 0.45 * w
        result.add(_c(f"✓ detections line up with ground truth "
                      f"({matched}/{placed} placed objects)", C.GREEN))
    else:
        result.add(_c(f"✗ only {matched}/{placed} placed objects matched "
                      f"(need {L1_MIN_RECALL:.0%}) — boxes may be in the wrong "
                      f"coordinate convention", C.YELLOW))

    # the CSV, round-tripped
    csv_path = grade_dir / "L1_out.csv"
    if not csv_path.exists():
        result.add(_c("✗ write_detections_csv produced no file", C.YELLOW))
    else:
        try:
            got = list(csv.DictReader(open(csv_path)))
            want = ["filename", "label", "score", "x1", "y1", "x2", "y2"]
            if got and list(got[0]) == want and len(got) == len(recs):
                earned += 0.35 * w
                result.add(_c(f"✓ detections.csv round-trips ({len(got)} rows)", C.GREEN))
            elif got:
                result.add(_c(f"✗ CSV columns are {list(got[0])}, expected {want}", C.YELLOW))
            else:
                result.add(_c("✗ CSV has a header but no rows", C.YELLOW))
        except Exception as e:  # noqa: BLE001
            result.add(_c(f"✗ CSV could not be read back ({e})", C.YELLOW))

    result.earned = round(earned, 4)
    result.status = "PASS" if earned >= 0.99 * w else "PARTIAL"


def check_l2(grade_dir: Path, result: LevelResult) -> None:
    # The expected values are computed here, by the grader's own `_iou`, rather
    # than written down. Two of the six were originally hardcoded from mental
    # arithmetic and two of those two were wrong -- Gate 1 failed the reference
    # solution on the grader's mistake. A constant nobody recomputes is a
    # constant nobody checks.
    # The last two miss on exactly one axis. They are the pairs that matter:
    # when the boxes miss on *both* axes the two negative sides multiply back
    # to a positive intersection, the union goes negative, and the `union > 0`
    # guard returns 0.0 by accident -- so an unclamped implementation scores
    # full marks on every symmetric case. Gate 4 caught that with a fixture
    # that passed L2 outright.
    pairs = [((0, 0, 10, 10), (0, 0, 10, 10)),
             ((0, 0, 10, 10), (50, 50, 60, 60)),
             ((0, 0, 10, 10), (5, 5, 15, 15)),
             ((0, 0, 10, 10), (10, 10, 20, 20)),
             ((2, 3, 12, 13), (4, 1, 14, 11)),
             ((0, 0, 100, 50), (25, 10, 75, 40)),
             ((0, 0, 10, 10), (20, 5, 30, 15)),
             ((0, 0, 10, 10), (5, 20, 15, 30))]
    exp_iou = np.array([_iou(a, b) for a, b in pairs], dtype=np.float64)
    rng = np.random.default_rng(11)
    xy = rng.uniform(0, 200, size=(40, 2)); wh = rng.uniform(10, 60, size=(40, 2))
    B = np.hstack([xy, xy + wh]); S = rng.uniform(0, 1, 40)
    L = ["face" if i % 3 else "other" for i in range(40)]
    keep = [i for i in range(40) if S[i] >= 0.5 and L[i] == "face"]
    check_parts(grade_dir, result, [
        ("L2_iou", "iou", exp_iou, 0.55, dict(atol=1e-9, rtol=1e-9,
            hint_values="check the no-overlap case: clamp the intersection "
                        "width and height at zero before multiplying")),
        ("L2_fb", "filter boxes", B[np.asarray(keep, dtype=np.int64)], 0.25,
            dict(atol=1e-12, rtol=1e-12)),
        ("L2_fs", "filter scores", S[np.asarray(keep, dtype=np.int64)], 0.10,
            dict(atol=1e-12, rtol=1e-12)),
        ("L2_fn", "filter labels", np.array([len(keep)], dtype=np.int64), 0.10, {}),
    ])


def check_l3(grade_dir: Path, result: LevelResult) -> None:
    import csv
    d = _load(grade_dir, "L3", result)
    if d is None:
        return
    w = result.weight
    earned = 0.0

    # Ground truth is looked up by the filenames the probe actually used
    # (d["files"]) rather than recomputed independently. An earlier version
    # re-read faces.csv here with its own [:L3_IMAGES] slice, unfiltered by
    # band -- when PROBE_L3's selection was changed to near-only, this line
    # was not, and the two lists silently went out of sync: near-only boxes
    # zipped position-by-position against a half-far row list, comparing each
    # box against the wrong image. The reference scored 4/40 instead of
    # 40/40, and nothing about it looked like an error -- it looked like a
    # detector that mostly missed. Keying by filename makes this class of
    # drift impossible rather than merely unlikely.
    by_filename = {r["filename"]: r for r in csv.DictReader(open(PROVIDED / "faces.csv"))}
    found = d["found"]
    if len(found) != len(d["files"]):
        result.status = "FAIL"
        result.add(_c("✗ detect_faces did not return one result per image", C.RED))
        return
    rows = [by_filename[f] for f in d["files"]]

    if all(len(f) == 0 for f in found):
        result.status = "FAIL"
        result.add(_c("✗ no faces found in any of 40 images, all from the "
                      "'near' band where the reference finds a face in every "
                      "one. This is a broken detector rather than a hard "
                      "corpus — check that the model path resolved and that "
                      "the image was handed over in the format MediaPipe "
                      "expects.", C.RED))
        return
    earned += 0.20 * w
    result.add(_c("✓ the detector runs and returns boxes", C.GREEN))

    hit = 0
    for r, boxes_ in zip(rows, found):
        tb = (float(r["x1"]), float(r["y1"]), float(r["x2"]), float(r["y2"]))
        if boxes_ and max(_iou(tb, tuple(float(v) for v in b)) for b in boxes_) > L3_IOU:
            hit += 1
    frac = hit / len(rows)
    if frac >= L3_MIN_BOXMATCH:
        earned += 0.45 * w
        result.add(_c(f"✓ boxes land on the faces ({hit}/{len(rows)})", C.GREEN))
    else:
        result.add(_c(f"✗ only {hit}/{len(rows)} boxes overlap the true face "
                      f"(need {L3_MIN_BOXMATCH:.0%}) — the detector reports an "
                      f"origin plus width and height, and the rest of the "
                      f"package expects corners", C.YELLOW))

    if not d["count_keys_ok"]:
        result.add(_c("✗ count_faces should key on filenames, not full paths", C.YELLOW))
    else:
        exact = sum(1 for r, c in zip(rows, d["count_vals"]) if int(r["n_faces"]) == c)
        if exact / len(rows) >= L3_MIN_COUNTMATCH:
            earned += 0.35 * w
            result.add(_c(f"✓ counts agree with the manifest ({exact}/{len(rows)})", C.GREEN))
        else:
            result.add(_c(f"✗ counts agree on only {exact}/{len(rows)} images", C.YELLOW))

    result.earned = round(earned, 4)
    result.status = "PASS" if earned >= 0.99 * w else "PARTIAL"


def check_l4(grade_dir: Path, result: LevelResult) -> None:
    err = grade_dir / "L4.error"
    if err.exists() and "read-only" in err.read_text():
        result.status = "FAIL"
        result.add(_c("✗ tried to write into the input array, which is "
                      "read-only because it came straight from an image file. "
                      "Build a new array and return that -- the caller still "
                      "needs the original.", C.RED))
        return
    d = _load(grade_dir, "L4", result)
    if d is None:
        return
    w = result.weight
    earned = 0.0

    if any(r["dtype"] != "uint8" or len(r["shape"]) != 3 for r in d):
        result.status = "PARTIAL"
        result.add(_c("✗ annotated image must be an (H, W, 3) uint8 array", C.YELLOW))
        result.earned = 0.0
        return
    earned += 0.20 * w
    result.add(_c("✓ returns an image of the right shape and type", C.GREEN))

    if any(r["mutated_input"] for r in d):
        result.add(_c("✗ the input array was modified in place — return a new "
                      "array, or the caller's copy is destroyed too", C.YELLOW))
    else:
        earned += 0.15 * w
        result.add(_c("✓ input left untouched", C.GREEN))

    changed = sum(r["changed"] for r in d)
    inside = sum(r["inside"] for r in d)
    if changed == 0:
        result.status = "PARTIAL"
        result.earned = round(earned, 4)
        result.add(_c("✗ the annotated image is identical to the input — "
                      "nothing was applied", C.YELLOW))
        return
    frac = inside / changed
    if frac >= L4_MIN_INSIDE:
        earned += 0.40 * w
        result.add(_c(f"✓ changes are concentrated on the faces "
                      f"({frac:.0%} of altered pixels)", C.GREEN))
    else:
        result.add(_c(f"✗ only {frac:.0%} of altered pixels fall inside a face "
                      f"box (need {L4_MIN_INSIDE:.0%}) — an effect applied to "
                      f"the whole frame is not a face-aware app", C.YELLOW))

    keys_ok = all({"n_faces", "mode", "coverage"} <= set(r["report_keys"]) for r in d)
    vals_ok = all(r["n_faces"] == 1 and 0.0 <= r["coverage"] <= 1.0 for r in d)
    if keys_ok and vals_ok:
        earned += 0.25 * w
        result.add(_c("✓ report is complete and sane", C.GREEN))
    elif keys_ok:
        result.add(_c(f"✗ report keys are present but the values are off "
                      f"(n_faces should be 1 here; coverage is a fraction)", C.YELLOW))
    else:
        result.add(_c("✗ report needs keys 'n_faces', 'mode' and 'coverage'", C.YELLOW))

    result.earned = round(earned, 4)
    result.status = "PASS" if earned >= 0.99 * w else "PARTIAL"


def check_l5(grade_dir: Path, result: LevelResult) -> None:
    d = _load(grade_dir, "L5", result)
    if d is None:
        return
    w = result.weight
    rates = d["rates"]

    # Broken vs unfair.  A student told to explain a subgroup gap when their
    # detector never fired will spend an evening on the wrong problem.
    if not rates:
        result.status = "FAIL"
        result.add(_c("✗ no groups returned — the manifest rows carry a 'group' "
                      "column and the result should be keyed on it", C.RED))
        return
    if all(v == 0.0 for v in rates.values()):
        result.status = "FAIL"
        result.add(_c("✗ every group scores zero. That is not a fairness "
                      "finding, it is a detector that never fired — fix L3 "
                      "first and this level will follow.", C.RED))
        return
    if all(v == 1.0 for v in rates.values()):
        result.status = "PARTIAL"
        result.earned = round(0.20 * w, 4)
        result.add(_c("✗ every group scores 1.0. The detector does not find "
                      "every face in this corpus, so this is likely counting "
                      "images rather than hits — check what you increment when "
                      "the detector returns an empty list.", C.YELLOW))
        return

    earned = 0.20 * w
    result.add(_c(f"✓ produced per-group rates ({', '.join(sorted(rates))})", C.GREEN))

    if set(rates) < {"near", "far"}:
        result.add(_c(f"✗ expected groups 'near' and 'far', got {sorted(rates)}", C.YELLOW))
    else:
        gap = rates["near"] - rates["far"]
        if gap >= L5_MIN_GAP:
            earned += 0.55 * w
            result.add(_c(f"✓ gap between groups is {gap:.2f} "
                          f"(near {rates['near']:.2f}, far {rates['far']:.2f}), "
                          f"clearing the {L5_MIN_GAP:.2f} floor", C.GREEN))
        else:
            result.add(_c(f"✗ gap is only {gap:.2f} (near {rates['near']:.2f}, "
                          f"far {rates['far']:.2f}), need at least {L5_MIN_GAP:.2f}. "
                          f"An image counts as a hit when the detector returns "
                          f"anything at all.", C.YELLOW))

    if d["worst"] == L5_WORST:
        earned += 0.25 * w
        result.add(_c(f"✓ identified '{d['worst']}' as the worst-served group", C.GREEN))
    else:
        result.add(_c(f"✗ worst_group returned '{d['worst']}'", C.YELLOW))

    result.earned = round(earned, 4)
    result.status = "PASS" if earned >= 0.99 * w else "PARTIAL"


def check_repo(grade_dir: Path, result: LevelResult) -> None:
    """Integration: every module present, importable, and actually written.

    An earlier version awarded this level in full to a repo in which every
    function still raised NotImplementedError -- it checked that the names were
    callable, which our own scaffold satisfies. Gate 2 caught it. Credit for
    the scaffold is credit for our work, so a module counts only once its
    functions have bodies.
    """
    d = _load(grade_dir, "REPO", result)
    if d is None:
        return
    w = result.weight
    share = w / len(d)
    earned = 0.0
    for mod in sorted(d):
        e = d[mod]
        if not e["imports"]:
            result.add(_c(f"✗ {mod} does not import: {e.get('error', '')}", C.RED))
        elif e["missing"]:
            result.add(_c(f"✗ {mod} is missing {', '.join(e['missing'])}", C.YELLOW))
        elif e["unwritten"]:
            result.add(_c(f"⋯ {mod} — not written yet: "
                          f"{', '.join(e['unwritten'])}", C.GREY))
        else:
            earned += share
            result.add(_c(f"✓ {mod}", C.GREEN))
    result.earned = round(earned, 4)
    result.status = "PASS" if earned >= 0.99 * w else ("FAIL" if earned == 0 else "PARTIAL")


def check_art(grade_dir: Path, result: LevelResult) -> None:
    d = _load(grade_dir, "ART", result)
    if d is None:
        return
    w = result.weight
    if not d.get("exists"):
        result.status = "FAIL"
        if d.get("build_error"):
            result.add(_c(f"✗ make_artifact.py could not build it: "
                          f"{d['build_error']}", C.RED))
        else:
            result.add(_c("✗ no artifact.png — run `python make_artifact.py` once "
                          "your app works", C.RED))
        return
    if "error" in d:
        result.status = "FAIL"
        result.add(_c(f"✗ artifact.png could not be opened ({d['error']})", C.RED))
        return

    earned = 0.35 * w
    result.add(_c(f"✓ artifact.png exists {tuple(d['shape'])}", C.GREEN))

    # A copy of a provided image, or a flat field, is not an artifact.
    if d["is_copy_of_provided"]:
        result.add(_c("✗ artifact.png is a byte-for-byte copy of a provided "
                      "image — nothing was applied to it", C.YELLOW))
    elif d["std"] < 1.0 or d["unique_colors"] < 32:
        result.add(_c("✗ artifact.png is nearly featureless", C.YELLOW))
    else:
        earned += 0.65 * w
        result.add(_c("✓ it is a real, altered image", C.GREEN))

    result.earned = round(earned, 4)
    result.status = "PASS" if earned >= 0.99 * w else "PARTIAL"


def check_bonus(grade_dir: Path, result: LevelResult) -> None:
    d = _load(grade_dir, "BONUS", result)
    if d is None:
        return
    w = result.weight
    if not d["agree"]:
        result.status = "FAIL"
        result.add(_c(f"✗ kept {d['n_mine']} boxes; the reference keeps "
                      f"{d['n_ref']}. Correctness first — the ordering is by "
                      f"descending score, and a suppressed box cannot suppress "
                      f"anything itself.", C.RED))
        return
    earned = 0.5 * w
    result.add(_c(f"✓ correct — {d['n_ref']} boxes survive", C.GREEN))
    if d["speedup"] >= BONUS_MIN_SPEEDUP:
        earned += 0.5 * w
        result.add(_c(f"✓ {d['speedup']:.1f}x faster than the nested-loop "
                      f"version (needed {BONUS_MIN_SPEEDUP:.0f}x)", C.GREEN))
        result.status = "PASS"
    else:
        result.add(_c(f"✗ only {d['speedup']:.1f}x faster (needed "
                      f"{BONUS_MIN_SPEEDUP:.0f}x) — the inner comparison "
                      f"against every remaining box is one array operation",
                      C.YELLOW))
        result.status = "PARTIAL"
    result.earned = round(earned, 4)


# --------------------------------------------------------------------------- #
LEVELS = [
    Level(name="L1", title="Inference", weight=12.0, probe=PROBE_L1, check=check_l1),
    Level(name="L2", title="Boxes", weight=18.0, probe=PROBE_L2, check=check_l2),
    Level(name="L3", title="Faces", weight=14.0, probe=PROBE_L3, check=check_l3),
    # L4 and L5 read faces the student's own L3 produced upstream, so they name
    # it in requires=.  The gate only stops a level whose upstream FAILed, not
    # one that scored PARTIAL, which is why both checks open with their own
    # broken-vs-weak branch rather than trusting the gate.
    Level(name="L4", title="The app", weight=22.0, probe=PROBE_L4, check=check_l4,
          requires=["L3"]),
    Level(name="L5", title="Who is it worse for", weight=18.0, probe=PROBE_L5,
          check=check_l5, requires=["L3"]),
    Level(name="REPO", title="The repo", weight=8.0, probe=PROBE_REPO, check=check_repo),
    Level(name="ART", title="The artifact", weight=8.0, probe=PROBE_ART, check=check_art),
    Level(name="BONUS", title="Suppression by hand", weight=10.0, probe=PROBE_BONUS,
          check=check_bonus, requires=["L2"], bonus=True),
]


def main() -> int:
    target = sys.argv[1] if len(sys.argv) > 1 else "."
    payload = run_grader(
        target, LEVELS,
        assignment_id=ASSIGNMENT_ID, assignment_title=ASSIGNMENT_TITLE,
        entry=ENTRY, repo_package=REPO_PACKAGE,
        strict=False, timeout=TIMEOUT, clean_outputs=CLEAN_OUTPUTS,
    )
    return 0 if payload["run_all_ok"] else 1


if __name__ == "__main__":
    sys.exit(main())
