"""
grader.py  --  Team Project: The Detector, and What It Misses
=============================================================

Score preview for students; the same file backs the instructor's batch
re-grade, which is the grade of record.

    python grader.py .

Entry mode is "repo": the engine imports `facedetect` in a fresh interpreter
and then runs every probe in that same process, in LEVELS order. The import is
this project's Restart & Run All.

Grading shapes used here
------------------------
The HOWTO names three. Timings decided which ones apply: BlazeFace covers all
550 images in under seven seconds and YOLO covers 24 scenes in fifteen, so the
probes can *call* the student's functions rather than reading whatever their
last run happened to leave on disk. That is the strongest of the three shapes
and it isolates a bug to the level that caused it.

    L1, L3      call and threshold, against ground truth from the manifests
    L2, BONUS   call and compare, on the grader's own boxes -- no corpus, no
                model, no version sensitivity
    L4, L5      call and threshold, with an explicit broken-vs-unfair branch
    REPO        structural
    ART         grade what the run produced -- the only level that reads an
                artifact instead of calling something

Measured, not guessed
---------------------
Every floor below was produced by running the reference implementation against
the shipped corpus and writing down where it landed. Re-run `sanity_tp.py`
after any change to the corpus or a library pin; the numbers are properties of
this data and this version of these two detectors, not constants of nature.
"""
